# ==========================================
# 10. CHATBOT LOOP
# ==========================================

print("\n🍰 Welcome to Sweet Crumbs Home Bakery!")
print("Type 'bye' to exit.\n")

while True:

    user_input = input("You: ").strip()

    if not user_input:
        continue

    if user_input.lower() in ("bye", "exit", "quit"):

        print("Bot: Thank you for visiting Sweet Crumbs!")
        break

    reply = chat(user_input)

    print("Bot:", reply)